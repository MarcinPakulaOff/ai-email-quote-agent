#!/usr/bin/env node
// Builds n8n/workflow.json from n8n/workflow.template.json:
//   "@@build:<name>@@"  in a Code node   → src modules listed in n8n/glue/<name>.js (// @inline …) + prompts (// @prompt …) + the glue
//   "@@prompt:<name>@@" in a model node  → prompts/<name>.txt
// One source of truth: the code n8n runs is the code the tests run.
// Usage: node scripts/build-workflow.mjs [--check]   (--check fails when workflow.json is out of date)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const read = (p) => readFileSync(root + p, 'utf8');

const stripModule = (src) => src.replace(/^export (const|function|class|let) /gm, '$1 ');

export function codeFor(name) {
  const glue = read(`n8n/glue/${name}.js`);
  const directive = (tag) => [...glue.matchAll(new RegExp(`^// @${tag} (.+)$`, 'gm'))].flatMap((m) => m[1].trim().split(/\s+/));
  const parts = [`// GENERATED by scripts/build-workflow.mjs from n8n/glue/${name}.js — edit the sources, not this node.`];
  for (const mod of directive('inline')) parts.push(`// ── src/${mod}.mjs ──`, stripModule(read(`src/${mod}.mjs`)));
  for (const p of directive('prompt')) parts.push(`const PROMPT_${p.toUpperCase()} = ${JSON.stringify(read(`prompts/${p}.txt`).trim())};`);
  parts.push('// ── glue ──', glue.replace(/^\/\/ @(inline|prompt) .+\n/gm, ''));
  return parts.join('\n');
}

export function build() {
  const wf = JSON.parse(read('n8n/workflow.template.json'));
  for (const node of wf.nodes) {
    const p = node.parameters;
    const m = typeof p.jsCode === 'string' && p.jsCode.match(/^@@build:([\w-]+)@@$/);
    if (m) p.jsCode = codeFor(m[1]);
    for (const r of p.responses?.values ?? []) {
      const pm = String(r.content).match(/^@@prompt:([\w-]+)@@$/);
      if (pm) r.content = read(`prompts/${pm[1]}.txt`).trim();
    }
  }
  return JSON.stringify(wf, null, 2) + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = build();
  if (process.argv.includes('--check')) {
    if (read('n8n/workflow.json') !== out) { console.error('n8n/workflow.json is out of date: run npm run build'); process.exit(1); }
    console.log('n8n/workflow.json is up to date');
  } else {
    writeFileSync(root + 'n8n/workflow.json', out);
    console.log('wrote n8n/workflow.json');
  }
}
